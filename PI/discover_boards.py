#!/usr/bin/env python3
"""Find every board on the USB hub and ask it who it is (step 1.7).

Each board is opened, given a moment to finish its reset, then asked STATUS.
The replies become the table that goes in Docs/boards.md.

    python3 discover_boards.py
    python3 discover_boards.py --markdown >> ../Docs/boards.md

Run it after flashing to confirm every board still knows its node ID, and
check the MACs against Docs/boards.md: a port answering with another label's
MAC means a sticker and the table disagree.
"""

from __future__ import annotations

import argparse
import os
import sys
import time
from dataclasses import dataclass, field

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from swarmlab.board import open_together
from swarmlab.ports import BAUD, find_ports


@dataclass
class Board:
    """What one port answered, or why it did not."""
    port: str
    fields: dict[str, str] = field(default_factory=dict)
    error: str = ""

    @property
    def node_id(self) -> str:
        return self.fields.get("id", "?")

    @property
    def label(self) -> str:
        return self.fields.get("label", "?")

    @property
    def mac(self) -> str:
        return self.fields.get("mac", "?")

    @property
    def lora(self) -> str:
        return self.fields.get("lora", "?")

    @property
    def oled(self) -> str:
        return self.fields.get("oled", "?")


def probe_all(ports: list[str], baud: int) -> list[Board]:
    """Asks every port for STATUS. One Board per port, in port order."""
    links, failed = open_together(ports, baud)
    by_port = {link.port: link for link in links}
    boards = []
    try:
        for port in ports:
            if port in failed:
                boards.append(Board(port, error=failed[port]))
                continue
            fields = by_port[port].status()
            if fields:
                boards.append(Board(port, fields=fields))
            else:
                boards.append(Board(port, error="no STATUS reply"))
    finally:
        for link in links:
            link.close()
    return boards


def print_table(boards: list[Board]) -> None:
    rows = [("PORT", "ID", "LABEL", "MAC", "LORA", "OLED", "NOTE")]
    for b in boards:
        rows.append(
            (b.port, b.node_id, b.label, b.mac, b.lora, b.oled, b.error or "")
        )
    widths = [max(len(r[i]) for r in rows) for i in range(len(rows[0]))]
    for i, row in enumerate(rows):
        print("  ".join(cell.ljust(widths[j]) for j, cell in enumerate(row)).rstrip())
        if i == 0:
            print("  ".join("-" * w for w in widths))


def print_markdown(boards: list[Board]) -> None:
    print()
    print(f"<!-- generated by discover_boards.py on {time.strftime('%Y-%m-%d %H:%M')} -->")
    print("| Label | ID | MAC | Hub port | by-path | Notes |")
    print("| --- | --- | --- | --- | --- | --- |")
    for b in boards:
        print(
            f"| {b.label} | {b.node_id} | {b.mac} |  | `{b.port}` | "
            f"{b.error or ''} |"
        )


def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--baud", type=int, default=BAUD)
    ap.add_argument(
        "--markdown",
        action="store_true",
        help="emit a Docs/boards.md table instead of the aligned table",
    )
    args = ap.parse_args()

    ports = find_ports()
    if not ports:
        print("No serial ports found.", file=sys.stderr)
        return 1

    print(f"Probing {len(ports)} port(s)...", file=sys.stderr)
    boards = probe_all(ports, args.baud)

    if args.markdown:
        print_markdown(boards)
    else:
        print_table(boards)

    answered = sum(1 for b in boards if not b.error)
    unset = sum(1 for b in boards if not b.error and b.node_id in ("0", "?"))
    print(f"\n{answered}/{len(boards)} board(s) answered.", file=sys.stderr)
    if unset:
        print(
            f"{unset} board(s) have no node ID. Send 'SETID <n>' to each one "
            "(step 1.4).",
            file=sys.stderr,
        )
    return 0 if answered == len(boards) else 1


if __name__ == "__main__":
    sys.exit(main())
